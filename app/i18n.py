def get_translation(key, lang=None):
    lang = lang or session.get('lang', 'en')
    if lang == 'el':
        paid = re.fullmatch(r'Order #(\d+) has been paid\.', key)
        if paid:
            return f'Η παραγγελία #{paid.group(1)} πληρώθηκε.'
        updated = re.fullmatch(r'Order #(\d+) is now (.+)\.', key)
        if updated:
            statuses = {
                'shipped': 'απεστάλη',
                'ready_for_pickup': 'είναι έτοιμη για παραλαβή',
                'completed': 'ολοκληρώθηκε',
            }
            status = statuses.get(updated.group(2), updated.group(2))
            return f'Η παραγγελία #{updated.group(1)} {status}.'
        message = re.fullmatch(r'New message for order #(\d+)\.', key)
        if message:
            return f'Νέο μήνυμα για την παραγγελία #{message.group(1)}.'
        failed = re.fullmatch(r'Payment failed for order #(\d+)\.', key)
        if failed:
            return f'Η πληρωμή για την παραγγελία #{failed.group(1)} απέτυχε.'
    return TRANSLATIONS.get(lang, TRANSLATIONS['en']).get(key, key)
